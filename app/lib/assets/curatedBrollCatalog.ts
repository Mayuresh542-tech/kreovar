/**
 * Convert a CuratedBrollItem to the StockVideo format expected by editor components
 */
export function curatedItemToStockVideo(item: CuratedBrollItem): StockVideo {
  return {
    id: item.id,
    title: item.title,
    thumbnail: item.thumbnail,
    videoUrl: item.videoUrl,
    duration: item.duration,
    width: item.width,
    height: item.height,
    creatorName: item.creatorName,
    creatorUrl: item.creatorUrl,
    sourcePage: item.sourcePage,
    source: "pexels", // Keep source as pexels/curated for seamless downstream compatibility
  };
}

/**
 * Retrieve curated B-roll clips by category
 */
export function getCuratedBrollByCategory(
  category: BrollNiche,
  orientation?: "portrait" | "landscape"
): CuratedBrollItem[] {
  let items = CURATED_BROLL_CATALOG.filter((item) => item.category === category);
  if (orientation) {
    items = items.filter((item) => item.orientation === orientation);
  }
  return items;
}

/**
 * Search the curated B-roll catalog by query, category, and orientation
 */
export function searchCuratedBroll(
  query: string,
  options: {
    category?: BrollNiche;
    orientation?: "portrait" | "landscape";
    minDuration?: number;
    limit?: number;
  } = {}
): StockVideo[] {
  const q = (query || "").trim().toLowerCase();
  const queryTokens = q.split(/\s+/).filter((t) => t.length > 1);

  let scored = CURATED_BROLL_CATALOG.map((item) => {
    let score = 0;

    // Category match
    if (options.category && item.category === options.category) {
      score += 15;
    }

    // Orientation match
    if (options.orientation && item.orientation === options.orientation) {
      score += 5;
    }

    if (!q) {
      return { item, score: score + 1 };
    }

    const titleLower = item.title.toLowerCase();
    const descLower = item.description.toLowerCase();
    const categoryLower = item.category.toLowerCase();
    const tagsLower = item.tags.map((t) => t.toLowerCase());

    // Exact phrase match
    if (titleLower.includes(q)) score += 20;
    if (descLower.includes(q)) score += 10;
    if (categoryLower.includes(q)) score += 15;
    if (tagsLower.includes(q)) score += 15;

    // Token matches
    for (const token of queryTokens) {
      if (titleLower.includes(token)) score += 8;
      if (tagsLower.some((t) => t.includes(token))) score += 6;
      if (descLower.includes(token)) score += 4;
      if (categoryLower.includes(token)) score += 6;
    }

    return { item, score };
  });

  // Filter duration if specified
  if (options.minDuration !== undefined) {
    const durationFiltered = scored.filter((entry) => entry.item.duration >= options.minDuration!);
    if (durationFiltered.length > 0) {
      scored = durationFiltered;
    }
  }

  // Filter orientation if strict
  if (options.orientation) {
    const matchingOrient = scored.filter((entry) => entry.item.orientation === options.orientation);
    if (matchingOrient.length > 0) {
      scored = matchingOrient;
    }
  }

  // Filter category if specified and has matches
  if (options.category) {
    const matchingCat = scored.filter((entry) => entry.item.category === options.category);
    if (matchingCat.length > 0) {
      scored = matchingCat;
    }
  }

  // Sort descending by score
  scored.sort((a, b) => b.score - a.score);

  const limit = options.limit || 12;
  const topItems = scored.slice(0, limit).map((entry) => curatedItemToStockVideo(entry.item));

  // Fallback: If no matches, return category items or general catalog items respecting orientation
  if (topItems.length === 0) {
    let pool = options.category
      ? getCuratedBrollByCategory(options.category, options.orientation)
      : CURATED_BROLL_CATALOG;
    if (options.orientation) {
      const orientFiltered = pool.filter((item) => item.orientation === options.orientation);
      if (orientFiltered.length > 0) pool = orientFiltered;
    }
    if (options.minDuration !== undefined) {
      const durFiltered = pool.filter((item) => item.duration >= options.minDuration!);
      if (durFiltered.length > 0) pool = durFiltered;
    }
    return pool.slice(0, limit).map(curatedItemToStockVideo);
  }

  return topItems;
}
